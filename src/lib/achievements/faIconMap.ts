export function semanticIconForAchievementIconKey(
  iconKey: string | null | undefined,
): SemanticIconKey | null {
  if (!iconKey) return null
  if (FINAL_FA_TO_SEMANTIC[iconKey]) return FINAL_FA_TO_SEMANTIC[iconKey]
  // Already a semantic key
  if (!iconKey.startsWith('fas ') && !iconKey.startsWith('fa ')) {
    return iconKey as SemanticIconKey
  }
  return null
}
