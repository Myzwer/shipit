const isGauntlet = (row) =>
  row.conditionType === 'offering_collection' &&
  Boolean(row.conditionConfig?.bar_key) &&
  row.groupKey === 'bar_gauntlets'

const isDavids = (row) => row.groupKey === 'drinking_with_davids'
const isFrozenCollection = (row) =>
  row.stableKey === 'working-drinkit-frozen-concoctions' ||
  row.stableKey === 'working-drinkit-license-to-chill'

const davids = drinkit.filter(isDavids)
const gauntlets = drinkit.filter(isGauntlet)
const frozen = drinkit.filter(isFrozenCollection)
const base = active.filter(
  (row) => !isDavids(row) && !isGauntlet(row) && !isFrozenCollection(row),
)

function stripInstallMeta(row) {
  const {
    finalCategory: _fc,
    verificationPending: _vp,
    iconClass: _ic,
    ...rest
  } = row
  return rest
}

function writeJson(relPath, value) {
  const abs = join(root, relPath)
  writeFileSync(abs, `${JSON.stringify(value, null, 2)}\n`)
  return abs
}

